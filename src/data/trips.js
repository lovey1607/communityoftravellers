try {
  const stored = localStorage.getItem('cot_dynamic_trips');
  if (stored) {
    localTrips = JSON.parse(stored);
  }
} catch (e) {
  console.warn('Failed to load dynamic trips from localStorage:', e);
}

const influencerHostIds = new Set(hosts.map(h => h.id));

export const trips = (Array.isArray(localTrips) 
  ? localTrips.filter(t => t && typeof t === 'object' && t.id && t.slug) 
  : defaultTrips).filter(t => influencerHostIds.has(t.hostId));

export function saveTrips() {
  try {
    localStorage.setItem('cot_dynamic_trips', JSON.stringify(trips));
  } catch (e) {
    console.warn('Failed to save dynamic trips to localStorage:', e);
  }
}

export async function syncTripsWithServer() {
  try {
    const res = await fetch('/api/trips');
    if (res.ok) {
      const serverTrips = await res.json();
      if (Array.isArray(serverTrips) && serverTrips.length > 0) {
        // Merge: start with defaultTrips, then add any server-only trips
        const existingIds = new Set(defaultTrips.map(t => t.id));
        const merged = [...defaultTrips];
        for (const st of serverTrips) {
          if (st && st.id && !existingIds.has(st.id)) {
            // Ensure required fields have defaults for crawled trips
            st.rating = st.rating || 4.5;
            st.reviewCount = st.reviewCount || 0;
            st.totalSeats = st.totalSeats || 15;
            st.bookedSeats = st.bookedSeats || 0;
            st.groupType = st.groupType || 'mixed';
            st.stayType = st.stayType || 'hotel';
            st.transportMode = st.transportMode || 'car';
            st.foodType = st.foodType || 'both';
            st.region = st.region || 'domestic';
            st.subRegion = st.subRegion || 'north-india';
            st.origin = st.origin || 'Delhi';
            st.currency = st.currency || 'INR';
            st.categories = st.categories || ['adventure'];
            st.gallery = st.gallery || [st.coverImage || 'https://images.unsplash.com/photo-1501555088652-021faa106b9b?w=800&q=80'];
            st.safetyNotes = st.safetyNotes || ['Experienced trip leader'];
            st.faq = st.faq || [];
            merged.push(st);
            existingIds.add(st.id);
          }
        }
        trips.length = 0;
        trips.push(...merged.filter(t => influencerHostIds.has(t.hostId)));
        saveTrips();
        return true;
      } else if (Array.isArray(serverTrips) && serverTrips.length === 0) {
        // Database is empty on server, initialize it with defaultTrips
        const initRes = await fetch('/api/trips/initialize', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(defaultTrips)
        });
        if (initRes.ok) {
          trips.length = 0;
          trips.push(...defaultTrips);
          saveTrips();
          return true;
        }
      }
    }
  } catch (e) {
    console.warn('Failed to sync trips with server:', e);
  }
  return false;
}

