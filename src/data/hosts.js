// Always use defaultHosts as the canonical source.
// localStorage cache is only used for dynamically added hosts (e.g., new registrations).
let localHosts = null;
try {
  const stored = localStorage.getItem('cot_dynamic_hosts');
  if (stored) {
    localHosts = JSON.parse(stored);
  }
} catch (e) {
  console.warn('Failed to load dynamic hosts from localStorage:', e);
}

// Merge: start with all defaultHosts, then add any localStorage-only hosts
const defaultHostIds = new Set(defaultHosts.map(h => h.id));
const mergedHosts = [...defaultHosts];
if (Array.isArray(localHosts)) {
  for (const lh of localHosts) {
    if (lh && typeof lh === 'object' && lh.id && lh.name && !defaultHostIds.has(lh.id)) {
      mergedHosts.push(lh);
    }
  }
}

export const hosts = mergedHosts;

export function saveHosts() {
  try {
    localStorage.setItem('cot_dynamic_hosts', JSON.stringify(hosts));
  } catch (e) {
    console.warn('Failed to save dynamic hosts to localStorage:', e);
  }
}

